/**
 * Writes Timefold's results on invented instances to a JSON file, the oracle for the
 * TypeScript solver (frontend/tests/oracle/). Runs only on request, because it takes
 * minutes:
 * <pre>
 * ./mvnw test -Dtest=TimefoldOracleTest -Doracle.out=../frontend/tests/oracle/timefold.json
 * </pre>
 * Optional: {@code -Doracle.seconds=10} (time limit per instance). Every instance carries
 * its full distance matrix in whole metres, so both sides compute with the same numbers.
 * Location ids are the matrix indices; shipment {@code i} has id {@code i}.
 */
@EnabledIfSystemProperty(named = "oracle.out", matches = ".+")
class TimefoldOracleTest {

    record OracleShipment(int ldmTenths, int pickup, int delivery) {
    }

    record OracleTruck(long id, int capacityLdmTenths) {
    }

    record OracleRoute(long truckId, List<Integer> shipments, long meters) {
    }

    record OracleCase(String name, long seed, long[][] distance, int base, boolean returnToBase,
            List<OracleShipment> shipments, List<OracleTruck> trucks, int timefoldSeconds,
            long hard, long medium, long soft, List<OracleRoute> routes) {
    }

    record OracleFile(String note, List<OracleCase> cases) {
    }

    /** Planar instance: points in km, straight-line distances rounded to whole metres. */
    private record Instance(String name, long seed, double[][] xy, int base, boolean returnToBase,
            List<OracleShipment> shipments, List<OracleTruck> trucks) {

        long[][] distance() {
            long[][] distance = new long[xy.length][xy.length];
            for (int a = 0; a < xy.length; a++) {
                for (int b = 0; b < xy.length; b++) {
                    distance[a][b] = Math.round(Math.hypot(xy[a][0] - xy[b][0], xy[a][1] - xy[b][1]) * 1000);
                }
            }
            return distance;
        }
    }

    @Test
    void writesTimefoldResults() throws Exception {
        Path out = Path.of(System.getProperty("oracle.out"));
        int seconds = Integer.parseInt(System.getProperty("oracle.seconds", "10"));
        List<Instance> instances = new ArrayList<>();
        instances.add(test7());
        for (int i = 0; i < 30; i++) {
            instances.add(random(1000 + i));
        }

        List<OracleCase> cases = new ArrayList<>();
        for (Instance instance : instances) {
            cases.add(solve(instance, seconds));
            System.out.printf("oracle %s: %d trucks, %d m%n", instance.name(), -cases.getLast().medium(),
                    -cases.getLast().soft());
        }
        Files.createDirectories(out.toAbsolutePath().getParent());
        String note = "Generated by backend/src/test/java/rs/rcva/optimization/oracle/TimefoldOracleTest.java"
                + " (Timefold " + seconds + " s per case). Invented data.";
        Files.writeString(out, JsonMapper.builder().build().writeValueAsString(new OracleFile(note, cases)));
    }

    private static OracleCase solve(Instance instance, int seconds) {
        long[][] distance = instance.distance();
        DistanceProvider provider = (from, to) -> distance[(int) from.id()][(int) to.id()];
        JobInput input = input(instance);

        RoutingSolver.Outcome outcome = new RoutingSolver(input, provider).solve(Duration.ofSeconds(seconds));
        HardMediumSoftScore score = outcome.score();
        assertThat(score.isFeasible()).as(instance.name()).isTrue();
        OptimizationResult result = outcome.result();
        assertThat(new SolutionValidator(provider).validate(input, result).violations()).as(instance.name()).isEmpty();

        List<OracleRoute> routes = result.routes().stream()
                .sorted(Comparator.comparingLong(RoutePlan::truckId))
                .map(r -> new OracleRoute(r.truckId(), r.stops().stream()
                        .filter(s -> s.type() == StopType.PICKUP)
                        .map(RouteStop::shipmentId).map(Long::intValue).sorted().toList(), r.totalMeters()))
                .toList();
        return new OracleCase(instance.name(), instance.seed(), distance, instance.base(), instance.returnToBase(),
                instance.shipments(), instance.trucks(), seconds,
                score.hardScore(), score.mediumScore(), score.softScore(), routes);
    }

    private static JobInput input(Instance instance) {
        List<Location> locations = IntStream.range(0, instance.xy().length)
                .mapToObj(i -> new Location(i, "L" + i, null, "XX", null, 0.0, 0.0, GeocodeStatus.OK))
                .toList();
        List<Shipment> shipments = IntStream.range(0, instance.shipments().size())
                .mapToObj(i -> {
                    OracleShipment s = instance.shipments().get(i);
                    return Test7Data.shipment(i, "S" + i, s.ldmTenths(), s.pickup(), s.delivery());
                })
                .toList();
        List<Truck> trucks = instance.trucks().stream()
                .map(t -> new Truck(t.id(), "T" + t.id(), t.capacityLdmTenths(), true, null, null, null))
                .toList();
        return new JobInput(shipments, trucks, locations, new BaseSettings(instance.base(), instance.returnToBase()));
    }

    /** Test 7 (Test7Data), with locations renumbered to matrix indices. */
    private static Instance test7() {
        double[][] xy = {{0, 0}, {-50, 0}, {100, 0}, {-50, 10}, {100, 10}, {50, 0}, {-100, 0}, {50, 10}, {-100, 10}};
        List<OracleShipment> shipments = List.of(
                new OracleShipment(60, 1, 2), new OracleShipment(60, 3, 4),
                new OracleShipment(40, 5, 6), new OracleShipment(40, 7, 8));
        List<OracleTruck> trucks = List.of(new OracleTruck(1, 100), new OracleTruck(2, 100),
                new OracleTruck(3, 100), new OracleTruck(4, 100));
        return new Instance("test7", 0, xy, 0, true, shipments, trucks);
    }

    /**
     * Three kinds, by seed: like the real file (pickups around the base, deliveries in a
     * region far away), several delivery regions, and points spread at random. 5 to 30
     * shipments; trailers of 13,6 LDM, in half of the instances mixed with 10,0 LDM trucks.
     */
    private static Instance random(long seed) {
        Random random = new Random(seed);
        int kind = (int) (seed % 3);
        int n = 5 + random.nextInt(26);
        List<double[]> xy = new ArrayList<>();
        xy.add(new double[] {150, 150});
        List<OracleShipment> shipments = new ArrayList<>();
        for (int i = 0; i < n; i++) {
            double[] pickup;
            double[] delivery;
            switch (kind) {
                case 0 -> {
                    pickup = point(random, 0, 0, 300, 300);
                    delivery = point(random, -200, 1500, 600, 400);
                }
                case 1 -> {
                    pickup = point(random, 0, 0, 300, 300);
                    Map<Integer, double[]> regions = Map.of(0, new double[] {-600, 1200}, 1, new double[] {500, 1300},
                            2, new double[] {900, 400});
                    double[] region = regions.get(random.nextInt(3));
                    delivery = point(random, region[0], region[1], 300, 300);
                }
                default -> {
                    pickup = point(random, -500, -500, 1500, 1500);
                    delivery = point(random, -500, -500, 1500, 1500);
                }
            }
            xy.add(pickup);
            xy.add(delivery);
            shipments.add(new OracleShipment(10 + random.nextInt(71), xy.size() - 2, xy.size() - 1));
        }
        int total = shipments.stream().mapToInt(OracleShipment::ldmTenths).sum();
        int trailers = total / 136 + 3;
        List<OracleTruck> trucks = new ArrayList<>();
        for (int i = 0; i < trailers; i++) {
            trucks.add(new OracleTruck(i + 1, 136));
        }
        if (seed / 3 % 2 == 1) {
            for (int i = 0; i < 3; i++) {
                trucks.add(new OracleTruck(trailers + i + 1, 100));
            }
        }
        boolean returnToBase = random.nextBoolean();
        return new Instance("random-" + seed, seed, xy.toArray(double[][]::new), 0, returnToBase, shipments, trucks);
    }

    private static double[] point(Random random, double x, double y, double width, double height) {
        return new double[] {x + random.nextInt((int) width), y + random.nextInt((int) height)};
    }
}
